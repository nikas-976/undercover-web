export function getPairsForTheme(themeId = "all") {
  if (themeId === "all") return Object.values(WORD_PAIRS).flat()
  return WORD_PAIRS[themeId] || []
}

export function getRandomWordPair(themeId = "all") {
  const pairs = getPairsForTheme(themeId)
  if (pairs.length === 0) return getPairsForTheme("all")[0]
  return pairs[Math.floor(Math.random() * pairs.length)]
}

export function getTotalPairs() {
  return Object.values(WORD_PAIRS).reduce((acc, arr) => acc + arr.length, 0)
}

export function getThemeConfig(themeId) {
  const key = themeId?.toUpperCase()
  return THEMES[key] || THEMES.ALL
}

